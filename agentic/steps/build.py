        risks, strat = ctx.bb.require("risks")["domain"], ctx.bb.require("validation_strategy")
        lines = [f"# {req['title']}", "", f"**Original request:** \"{req['raw']}\"", "",
                 "## 1. Normalised problem", "", req["problem_statement"], "", "## 2. Clarifications and assumptions", ""]
        if req["ambiguities"]:
            lines.append(_table(["ID", "Vague term", "Question", "Resolved by", "Resolution"], [
                [a["id"], a["term"], a["question"], req["resolved_by"].get(a["id"], "assumption"),
                 (ctx.bb.get("input", {}).get("answers") or {}).get(a["id"]) or a["default"]] for a in req["ambiguities"]]))
        pending = [a for a in req["assumptions"] if a["needs_confirmation"]]
        lines += ["", "Assumptions needing confirmation:"] + ([f"- {a['text']} (confidence: {a['confidence']})" for a in pending] or ["- none: every ambiguity was answered by a human"])
        lines += ["", "## 3. Measurable objectives and options", ""]
        for o in opts["objectives"]:
            lines += [f"### {o['objective']} ({o['facet']})", f"- **Target:** {o['target']} _(source: {o['target_source']})_",
                      f"- **Metric:** {o['metric']}", "",
                      _table(["Option", "Gain", "Cost", "Risk", "Already in codebase?"],
                             [[x["name"], x["gain"], x["cost"], x["risk"], f"yes: `{x['exists']}`" if x.get("exists") else "no"] for x in o["options"]]),
                      "", f"**Recommendation (gap-aware):** {o['recommended']}", ""]
        if opts["impacted_flows"]:
            lines += ["## 4. Impacted flows in the existing system", ""] + [f"- `{r}`" for r in opts["impacted_flows"]] + [""]
        lines += ["## 5. Risks", "", _table(["ID", "Risk", "Mitigation"], [[r["id"], r["risk"], r["mitigation"]] for r in risks]), "",
                  "## 6. Validation plan", "", _table(["Layer", "Scope", "Gate"], [[x["layer"], x["scope"], x["gate"]] for x in strat["layers"]]), "",
                  "## 7. Acceptance criteria", ""] + [f"- {a}" for a in req["acceptance_criteria"]]
        lines += ["", "## 8. Status", "", "Implementation is intentionally **not** generated: the objectives above must be confirmed by a human first "
                  "(see the engineering summary for the approval record)."]
        return {"docs/PROPOSAL.md": "\n".join(lines) + "\n"}
