def render(text: str, params: Dict[str, str]) -> str:
    def sub(m: "re.Match[str]") -> str:
        key = m.group(1)
        if key not in params:
            raise FatalError(f"unknown template placeholder {{{{{key}}}}}")
        return params[key]
    return re.sub(r"\{\{([A-Z_]+)\}\}", sub, text)


def template_files(subdir: str) -> List[Tuple[str, str]]:
    root = TEMPLATES / subdir
    out = []
    for p in sorted(root.rglob("*.tmpl")):
        rel = p.relative_to(root).as_posix()[: -len(".tmpl")]
        out.append((rel, p.read_text(encoding="utf-8")))
    return out


def _params(ctx) -> Dict[str, str]:
    return {"SERVICE_NAME": "url-shortener", "CODE_LENGTH": "7", "REDIRECT_STATUS": "302", "RATE_LIMIT": "120"}


class CodeGenerator:
    name = "code_generator"

    def run(self, ctx) -> Dict[str, Any]:
        contract = ctx.bb.require("contract")  # coordination: code is generated against the published contract
        ctx.bb.require("schema")
        params = _params(ctx)
        defect = ctx.chaos.should_emit_defect(ctx.task)
        if ctx.feedback:
            ctx.note("applying repair feedback", findings=len(ctx.feedback),
                     first=ctx.feedback[0]["message"][:100])
        written = []
        for rel, text in template_files("urlshortener"):
            if rel.startswith("tests/"):
                continue
            content = render(text, params)
            if defect and rel == "shortener/app.py":
                # simulated generation flaw: the stats route is never registered
                content = content.replace('@router.route("GET", "/api/v1/links/{code}/stats", auth=True)\n', "")
                ctx.note("[chaos] emitting flawed app.py (stats route missing)")
            kind = "code" if rel.startswith(("shortener/", "scripts/")) else "config"
            ctx.write(rel, content, kind)
            written.append(rel)
        return {"files": written, "operations_targeted": len(contract["operations"])}


class TestGenerator:
    name = "test_generator"

    def run(self, ctx) -> Dict[str, Any]:
        pt = ctx.requirement["plan_type"]
        strategy = ctx.bb.get("validation_strategy")
        written = []
        if pt == "greenfield":
            ctx.bb.require("contract")
            for rel, text in template_files("urlshortener"):
                if rel.startswith("tests/"):
                    ctx.write(rel, render(text, _params(ctx)), "test")
                    written.append(rel)
            ac = SHORTENER_AC_TESTS
            body = ["# Acceptance-criteria traceability", "",
                    "Generated by `test_generator`; verified by the validator (every row must resolve to a real test).", "",
                    "| Criterion | Test |", "|---|---|"]
            body += [f"| {k} | `{v}` |" for k, v in ac.items()]
            if strategy:
                body += ["", "## Risk coverage", "", "| Risk | Covered by |", "|---|---|"]
                body += [f"| {t['risk']} | `{t['covered_by']}` |" for t in strategy["traceability"]]
            ctx.write("tests/TRACEABILITY.md", "\n".join(body) + "\n", "doc")
            written.append("tests/TRACEABILITY.md")
        elif pt == "brownfield_change":
            ctx.bb.require("contract")
            for rel, text in template_files("expiry"):
                ctx.write("tests/" + rel, render(text, _params(ctx)), "test")
                written.append("tests/" + rel)
            try:
                base = ctx.ws.read_baseline("tests/TRACEABILITY.md")
            except FileNotFoundError:
                base = "# Acceptance-criteria traceability\n"
            extra = ["", "## CHG-001 link expiry", "", "| Criterion | Test |", "|---|---|"]
            extra += [f"| {k} | `{v}` |" for k, v in EXPIRY_AC_TESTS.items()]
            if strategy:
                extra += ["", "### Risk coverage", "", "| Risk | Covered by |", "|---|---|"]
                extra += [f"| {t['risk']} | `{t['covered_by']}` |" for t in strategy["traceability"]]
            ctx.write("tests/TRACEABILITY.md", base.rstrip("\n") + "\n" + "\n".join(extra) + "\n", "doc")
