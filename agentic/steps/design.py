class ChangeDesigner:
    """Impact-driven change design for an existing system."""
    name = "change_designer"

    def run(self, ctx) -> Dict[str, Any]:
        req, impact = ctx.requirement, ctx.bb.require("impact")
        if req.get("change_recipe") != "expiry":
            raise FatalError("no change recipe available for this requirement")
        design = {
            "summary": "Add nullable links.expires_at, enforce at read time, expose optional expires_in_seconds on create.",
            "decisions": [
                {"id": "CHG-ADR-1", "title": "Store absolute expires_at (UTC ISO-8601), not a TTL",
                 "why": "Absolute time survives restarts, replicas and cache layers; TTL would need creation time + arithmetic everywhere.",
                 "tradeoffs": "Clients cannot extend by editing a TTL; extension needs a new endpoint (out of scope)."},
                {"id": "CHG-ADR-2", "title": "Expiry enforced at read time on the (possibly cached) Link object",
                 "why": "A cache fill-time check would serve expired links until TTL; evaluating on each resolve is O(1) and exact.",
                 "tradeoffs": "One timestamp comparison per redirect (negligible)."},
                {"id": "CHG-ADR-3", "title": "HTTP 410 Gone for expired links (404 stays for unknown/deleted)",
                 "why": "Lets clients/crawlers distinguish 'was valid' from 'never existed'.",
                 "tradeoffs": "Reveals that a code once existed (acceptable: codes are non-secret)."},
                {"id": "CHG-ADR-4", "title": "Additive, nullable column via migration v2 (no backfill)",
                 "why": "Zero-downtime: old code ignores the column, NULL = never expires, no table rewrite.",
                 "tradeoffs": "Expired rows are retained until a purge job exists (follow-up)."},
            ],
            "touch_points": {"modules": impact["modules"], "routes": impact["routes"], "tables": impact["tables"]},
            "rollout": ["deploy migration v2 (additive)", "deploy new code (reads/writes expires_at)",
                        "enable client usage", "rollback = redeploy old code; column is ignored"],
            "out_of_scope": ["purge job for expired rows", "extending expiry of an existing link"],
        }
        ctx.bb.set("change_design", design)
        return {"decisions": len(design["decisions"])}


class ContractDelta:
    name = "contract_delta"

    def run(self, ctx) -> Dict[str, Any]:
        old = json.loads(ctx.ws.read_baseline("openapi.json"))  # always derive from the pristine baseline
        ctx.bb.set("contract_baseline", {"operations": operations(old), "spec": old})
        spec = copy.deepcopy(old)
        try:
            props = spec["components"]["schemas"]["CreateLinkRequest"]["properties"]
            props["expires_in_seconds"] = {"type": "integer", "minimum": 60, "maximum": 31536000,
                                           "description": "Optional lifetime; link returns 410 Gone afterwards."}
            spec["components"]["schemas"]["Link"]["properties"]["expires_at"] = {
                "type": "string", "format": "date-time", "nullable": True}
            spec["paths"]["/{code}"]["get"]["responses"]["410"] = _err("Link has expired")
        except KeyError as exc:
            raise FatalError(f"baseline OpenAPI is missing expected element {exc}; cannot apply delta")
        spec["info"]["version"] = "1.1.0"
        ctx.write("openapi.json", json.dumps(spec, indent=2) + "\n", "contract")
        ctx.bb.set("contract", {"version": "1.1.0", "operations": operations(spec)})
        return {"added": ["expires_in_seconds", "expires_at", "410"]}


class MigrationDesigner:
    name = "migration_designer"

    def run(self, ctx) -> Dict[str, Any]:
        sql = ctx.ws.read_baseline("schema.sql")
        marker = "    deleted_at TEXT\n);"
        if sql.count(marker) != 1:
            raise FatalError("schema.sql anchor drift: cannot locate links table end")
        sql = sql.replace(marker, "    deleted_at TEXT,\n    expires_at TEXT\n);")
        ctx.write("schema.sql", sql, "schema")
        tables = _col_names(SCHEMA_V1)
        tables["links"] = tables["links"] + ["expires_at"]
        ctx.bb.set("schema", {"version": 2, "tables": tables})
        return {"migration": "v2: ALTER TABLE links ADD COLUMN expires_at TEXT"}


