class OptionsDesigner:
    """For an ambiguous / exploratory requirement: turn resolved goals into
    measurable objectives with design options and trade-offs."""
    name = "options_designer"

    OPTIONS = {
        "performance": {
            "objective": "Reduce redirect latency",
            "metric": "redirect p95 latency under 1k rps (server-side, ms)",
            "options": [
                {"name": "Read-through cache for resolve", "gain": "high", "cost": "low", "risk": "stale after delete (bounded by TTL)"},
                {"name": "Redis shared cache", "gain": "high", "cost": "medium", "risk": "new dependency + network hop"},
                {"name": "CDN edge caching with 301", "gain": "very high", "cost": "medium", "risk": "analytics under-count, hard to revoke"},
                {"name": "DB read replicas / sharding", "gain": "medium", "cost": "high", "risk": "operational complexity; only helps if DB is the bottleneck"}],
            "recommended": "Measure first. Then read-through cache (already present?) -> Redis -> CDN only if analytics permit."},
        "security": {
            "objective": "Reduce abuse and unauthorised use",
            "metric": "abuse requests blocked / false-positive rate; unauthenticated writes = 0",
            "options": [
                {"name": "API-key auth + per-key quotas", "gain": "high", "cost": "low", "risk": "key distribution/rotation"},
                {"name": "Distributed rate limiting (Redis)", "gain": "medium", "cost": "medium", "risk": "limiter outage policy (fail open/closed)"},
                {"name": "URL reputation screening (Safe Browsing)", "gain": "high", "cost": "medium", "risk": "latency + external dependency"},
                {"name": "Abuse reporting + takedown workflow", "gain": "medium", "cost": "medium", "risk": "process/staffing"}],
            "recommended": "API keys + quotas now; reputation screening asynchronous with shadow mode first."},
        "availability": {
            "objective": "Meet availability targets", "metric": "monthly availability %, RPO/RTO",
            "options": [{"name": "Multi-AZ replicated datastore", "gain": "high", "cost": "medium", "risk": "failover testing"}],
            "recommended": "Multi-AZ datastore + health-checked load balancing."},
        "scalability": {
            "objective": "Scale to target load", "metric": "sustained rps at p95 target",
            "options": [{"name": "Horizontal scale-out of stateless tier", "gain": "high", "cost": "low", "risk": "datastore becomes bottleneck"}],
            "recommended": "Scale out + load-test to find the first bottleneck."},
        "generic": {
            "objective": "Define 'better'", "metric": "to be agreed with stakeholders",
            "options": [{"name": "Workshop to define success metric", "gain": "n/a", "cost": "low", "risk": "delay"}],
            "recommended": "Do not build until a metric exists."},
    }

    OPTION_EXISTING = {  # option name -> capability key detected in the codebase
        "Read-through cache for resolve": "cache",
        "Distributed rate limiting (Redis)": "rate_limit",
        "API-key auth + per-key quotas": "auth",
    }

    @staticmethod
    def existing_capabilities(ctx) -> Dict[str, str]:
        """Gap analysis input: what the existing system already provides (from the AST model + source)."""
        from pathlib import Path
        model, req = ctx.bb.get("codebase_model"), ctx.requirement
        if not model or not req.get("target_repo"):
            return {}
        found: Dict[str, str] = {}
        for mod, info in model["modules"].items():
            for cls in info["classes"]:
                low = cls.lower()
                if "cache" in low:
                    found["cache"] = f"{mod}:{cls}"
                if "limiter" in low or "ratelimit" in low:
                    found["rate_limit"] = f"{mod}:{cls}"
                if "recorder" in low:
                    found["async_analytics"] = f"{mod}:{cls}"
            text = (Path(req["target_repo"]) / mod).read_text(encoding="utf-8").lower()
            if re.search(r"""get\(\s*["']x-api-key["']""", text):  # an actual header read, not a comment or config doc
                found["auth"] = f"{mod} (X-API-Key check, enforced only when keys are configured)"
        return found

    def run(self, ctx) -> Dict[str, Any]:
        req = ctx.requirement
        facets = req["concerns"] or ["generic"]
        existing = self.existing_capabilities(ctx)
        out = []
        for facet in facets:
            opt = copy.deepcopy(self.OPTIONS[facet])
            amb = next((a for a in req["ambiguities"] if a["facet"] == facet), None)
            target = (ctx.bb.get("input", {}).get("answers") or {}).get(amb["id"]) if amb else None
            opt["facet"] = facet
            opt["target"] = target or (amb["default"] if amb else "to be defined")
            opt["target_source"] = "human answer" if target else "analyst default (needs confirmation)"
            opt["already_present"] = []
            for o in opt["options"]:
                key = self.OPTION_EXISTING.get(o["name"])
                o["exists"] = existing.get(key, "") if key else ""
                if o["exists"]:
                    opt["already_present"].append(f"{o['name']}: {o['exists']}")
            if facet == "performance" and "cache" in existing:
                opt["recommended"] = (f"A read-through TTL/LRU cache already exists ({existing['cache']}). Do not rebuild it: "
                                      "capture a baseline with the load smoke script, then add Redis -> CDN only if the target is still missed.")
            if facet == "security" and "auth" in existing:
                opt["recommended"] = (f"API-key auth exists ({existing['auth']}) and a limiter exists "
                                      f"({existing.get('rate_limit', 'none')}) but it is per-client/per-node. Gap to close: make keys mandatory "
                                      "in production, add per-key quotas, share limiter state across nodes; reputation screening later in shadow mode.")
            out.append(opt)
        impact = ctx.bb.get("impact") or {}
        ctx.bb.set("options", {"objectives": out, "impacted_flows": impact.get("routes", []),
                               "impacted_modules": impact.get("modules", []), "existing": existing})
        return {"objectives": len(out), "existing_capabilities": sorted(existing)}


