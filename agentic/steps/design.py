SCHEMA_V1 = {
    "links": [("code", "TEXT PRIMARY KEY"), ("long_url", "TEXT NOT NULL"), ("created_at", "TEXT NOT NULL"),
              ("deleted_at", "TEXT")],
    "click_events": [("id", "INTEGER PRIMARY KEY AUTOINCREMENT"), ("code", "TEXT NOT NULL"), ("ts", "TEXT NOT NULL"),
                     ("visitor_hash", "TEXT NOT NULL"), ("referrer", "TEXT"), ("device", "TEXT NOT NULL")],
    "click_daily": [("code", "TEXT NOT NULL"), ("day", "TEXT NOT NULL"), ("clicks", "INTEGER NOT NULL"),
                    ("PRIMARY KEY", "(code, day)")],
}
INDEXES_V1 = ["CREATE INDEX idx_click_events_code_ts ON click_events (code, ts);"]


def render_schema_sql(tables: Dict[str, List], indexes: List[str]) -> str:
    out = ["-- Canonical schema (generated by data_modeler; storage.py migrations must produce the same tables)\n"]
    for table, cols in tables.items():
        body = ",\n".join(f"    {n} {t}" for n, t in cols)
        out.append(f"CREATE TABLE {table} (\n{body}\n);\n")
    out.extend(i + "\n" for i in indexes)
    return "\n".join(out)


def _col_names(tables: Dict[str, List]) -> Dict[str, List[str]]:
    return {t: [n for n, _ in cols if n != "PRIMARY KEY"] for t, cols in tables.items()}


class DataModeler:
    name = "data_modeler"

    def run(self, ctx) -> Dict[str, Any]:
        ctx.write("schema.sql", render_schema_sql(SCHEMA_V1, INDEXES_V1), "schema")
        ctx.bb.set("schema", {"version": 1, "tables": _col_names(SCHEMA_V1)})
        return {"tables": list(SCHEMA_V1)}


def _err(desc: str) -> Dict[str, Any]:
    return {"description": desc, "content": {"application/json": {"schema": {"$ref": "#/components/schemas/Error"}}}}


