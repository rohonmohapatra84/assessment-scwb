def operations(spec: Dict[str, Any]) -> List[Dict[str, Any]]:
    ops = []
    for path, item in spec["paths"].items():
        for method, op in item.items():
            ops.append({"method": method.upper(), "path": path, "statuses": sorted(op["responses"]),
                        "id": op.get("operationId")})
    return sorted(ops, key=lambda o: (o["path"], o["method"]))


class ContractDesigner:
    name = "contract_designer"

    def run(self, ctx) -> Dict[str, Any]:
        spec = build_openapi()
        ctx.write("openapi.json", json.dumps(spec, indent=2) + "\n", "contract")
        ops = operations(spec)
        ctx.bb.set("contract", {"version": spec["info"]["version"], "operations": ops})
        ctx.note("OpenAPI contract published", operations=len(ops))
        return {"operations": len(ops)}


